#!/usr/bin/env python3
"""Generate antialiased 4-bit Lato glyphs for the UI type scale. Requires Pillow and Lato."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

LATO = "/usr/share/fonts/truetype/lato/"
OUT = Path(__file__).resolve().parents[1] / "include" / "lato_font.h"
# (file, pixel size, C name). SemiBold for UI and headings, Regular for body text.
FONTS = (
    ("Lato-Semibold.ttf", 16, "font_s16"),
    ("Lato-Semibold.ttf", 20, "font_s20"),
    ("Lato-Semibold.ttf", 28, "font_s28"),
    ("Lato-Semibold.ttf", 40, "font_s40"),
    ("Lato-Semibold.ttf", 56, "font_s56"),
    ("Lato-Regular.ttf", 18, "font_r18"),
    ("Lato-Regular.ttf", 20, "font_r20"),
)
result = ["// Generated by tools/generate_font.py; Lato is licensed under the SIL OFL 1.1.",
          "#pragma once", "#include <stdint.h>",
          "struct FontGlyph { uint32_t offset; uint8_t width, advance; };",
          "struct BitmapFont { const uint8_t *data; const FontGlyph *glyphs; uint8_t height; };"]
for file, size, name in FONTS:
    face = ImageFont.truetype(LATO + file, size)
    ascent, descent = face.getmetrics()
    height = ascent + descent
    data, glyphs = [], []
    for code in range(32, 127):
        char = chr(code)
        advance = max(1, round(face.getlength(char)))
        width = max(advance, face.getbbox(char)[2])
        image = Image.new("L", (width, height))
        ImageDraw.Draw(image).text((0, 0), char, font=face, fill=255, stroke_width=0)
        pixels = image.get_flattened_data() if hasattr(image, "get_flattened_data") else image.getdata()
        levels = [(pixel + 8) // 17 for pixel in pixels]
        offset = len(data)
        for i in range(0, len(levels), 2):
            data.append((levels[i] << 4) | (levels[i+1] if i+1 < len(levels) else 0))
        glyphs.append((offset, width, advance))
    result.append(f"static const uint8_t {name}_data[] = {{")
    for i in range(0, len(data), 20): result.append("  " + ",".join(map(str, data[i:i+20])) + ",")
    result.append("};")
    result.append(f"static const FontGlyph {name}_glyphs[] = {{")
    result.extend(f"  {{{o},{w},{a}}}," for o,w,a in glyphs)
    result.append("};")
    result.append(f"static const BitmapFont {name} = {{{name}_data, {name}_glyphs, {height}}};")
OUT.write_text("\n".join(result) + "\n")
